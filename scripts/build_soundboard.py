#!/usr/bin/env python3
"""Build the offline catalog from all categorized recordings and game-menu assignments."""
import argparse
import json
from pathlib import Path
from extract_taunts import battlecry_variants

PERSONAL = ['Yes', 'No', 'Help', 'Got your back', 'Thanks', "You're welcome", 'Sorry', 'Taunt', 'Laugh', 'Respect']
TACTICAL = ['Follow me', 'Forward', 'Retreat', 'Kill archers', 'Objective', 'Hold your ground', 'Defend me', 'Incoming', 'Behind us', 'All clear']


def build(root, allow_missing=False):
    manifest = json.loads((root / 'taunts.json').read_text())
    lookup = {}
    categorized = {}
    for record in manifest['files']:
        voice = (record['faction'], record['class'])
        for name in record['category_files']:
            if name != 'Other':
                categorized.setdefault((*voice, name), []).append(record)
        if 'Battle cry' in record['voice_types']:
            categorized.setdefault((*voice, 'Battle cry'), []).append(record)
        for source in record['sources']:
            key = (record['faction'], record['class'], Path(source['package']).stem.lower(), source['export_index'])
            lookup[key] = record
    catalog = {}
    for assignment in manifest['menu_coverage']:
        faction, cls = assignment['faction'], assignment['class']
        group = {'XMenuVOSounds': 'personal', 'ZMenuVOSounds': 'tactical', 'BattleCrySound': 'battlecry'}[assignment['menu']]
        slot = int(assignment['slot']) if assignment['slot'] else 0
        name = (PERSONAL if group == 'personal' else TACTICAL)[slot] if group != 'battlecry' else 'Battle cry'
        # Keep the original menu takes first, preserving existing version numbers.
        # Then add map-specific, alternate, barbarian and legacy category recordings.
        records = []
        for wave in assignment['waves']:
            records.append(lookup[(faction, cls, wave['package'], wave['export_index'])])
        records.extend(categorized.get((faction, cls, name), []))
        commands = catalog.setdefault(faction, {}).setdefault(cls, {'personal': [], 'tactical': [], 'battlecry': []})
        variants = [(0, 'animated'), (1, 'running')] if group == 'battlecry' else [(slot, None)]
        for command_slot, variant in variants:
            command_name = f'Battle cry ({variant})' if variant else name
            clips, seen = [], set()
            for record in records:
                if variant and variant not in battlecry_variants(record):
                    continue
                if record['source_ogg_sha256'] in seen:
                    continue
                seen.add(record['source_ogg_sha256'])
                path = record['category_files'].get(command_name, record['file'])
                if not allow_missing and not (root / path).is_file():
                    raise ValueError(f'Missing audio: {path}; use --allow-missing for a partial collection')
                clips.append({'file': path, 'duration': round(record['duration_seconds'], 2)})
            if not clips:
                raise ValueError(f'Empty command: {faction}/{cls}/{command_name}')
            commands[group].append({'id': f'{group}-{command_slot}', 'name': 'Go for the Objective' if command_name == 'Objective' else command_name, 'slot': command_slot, 'clips': clips})
    for classes in catalog.values():
        if len(classes) != 4:
            raise ValueError('Missing classes')
        for groups in classes.values():
            for group, expected in [('personal', 10), ('tactical', 10), ('battlecry', 2)]:
                groups[group].sort(key=lambda c: c['slot'])
                if len(groups[group]) != expected:
                    raise ValueError(f'Incorrect {group} coverage')
    if len(catalog) != 2:
        raise ValueError('Missing faction')
    destination = root / 'soundboard/catalog.js'
    destination.parent.mkdir(exist_ok=True)
    destination.write_text('// Generated by scripts/build_soundboard.py.\nwindow.CHIVALRY_CATALOG = ' + json.dumps(catalog, separators=(',', ':'), ensure_ascii=False) + ';\n'
                          + 'window.CHIVALRY_AUDIO_ALIASES = ' + json.dumps(manifest.get('audio_path_aliases', {}), separators=(',', ':')) + ';\n')
    print(f'Built {destination.relative_to(root)}: 8 voices, 176 commands.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1] / 'website')
    parser.add_argument('--allow-missing', action='store_true', help='Retain metadata entries for intentionally removed audio; the websites filter unavailable files')
    args = parser.parse_args()
    build(args.root, allow_missing=args.allow_missing)
